"""
mission4.py -- Mission 4: would the model fit inside the doorbell (ESP32-S3)?

    python mission4.py                  # uses model/config.json and results/bench_*.csv
    python mission4.py --widths 32 128 256 512 2048

Every size number comes from app/stats.layer_table(), the SAME function that serves
GET /model_info, applied to real BatteryNet objects. Nothing here is typed in by hand.

Writes:
  results/mission4_widths.csv     the 5 -> w -> w -> 1 table
  docs/mission4_results.md        every table below, ready to paste into the report
  plots/mission4_memory.png       weight memory against width, with the SRAM and PSRAM lines
"""
import argparse
import csv
import glob
import json
import math
import os

import numpy as np

from app.model import FEATURES, BatteryNet
from app.stats import (BYTES_F32, BYTES_INT8, PSRAM_BYTES, SRAM_BUDGET_BYTES,
                       layer_table, peak_activation_values)

# ---------------------------------------------------------------------------------------
# Board speed assumption, with its source.
# Espressif ESP-DSP benchmarks (docs.espressif.com/projects/esp-dsp, "ESP-DSP Benchmarks"):
# dsps_dotprod_f32 with N = 256 takes 432 cycles on the ESP32-S3 with the optimised
# assembly kernel, and 1311 cycles with the plain-C ("ANSI") version.
# A dot product of length N is N multiply-accumulates, so:
CPU_HZ = 240e6                         # ESP32-S3 core clock (dual Xtensa LX7, we use one)
CYCLES_PER_MAC = {"optimised (ESP-DSP)": 432 / 256,   # ~1.69 cycles per MAC
                  "plain C": 1311 / 256}             # ~5.12 cycles per MAC
# ReLU, loop overhead and the copy-in of 5 inputs are ignored, so these are LOWER bounds;
# we report a 2x safety margin as a realistic figure.
OVERHEAD_FACTOR = 2.0
# ---------------------------------------------------------------------------------------


def fmt_bytes(n):
    return f"{n:,} B ({n / 1024:,.1f} KiB)" if n < 1024 ** 2 else f"{n:,} B ({n / 1024 ** 2:,.2f} MiB)"


def tick(x):
    return "yes" if x else "NO"


def params_w(w):
    """Closed form for 5 -> w -> w -> 1: (5w + w) + (w*w + w) + (w + 1) = w^2 + 8w + 1."""
    return w * w + 8 * w + 1


def largest_fitting_width(budget, bytes_per_param):
    """Largest w with bytes_per_param * (w^2 + 8w + 1) <= budget.

    Solve w^2 + 8w + (1 - budget/bytes) = 0 with the quadratic formula and take the floor.
    Then confirm on real networks with layer_table (so the closed form is checked, not trusted).
    """
    c = 1 - budget / bytes_per_param
    w = math.floor((-8 + math.sqrt(64 - 4 * c)) / 2)
    key = "total_bytes_f32" if bytes_per_param == BYTES_F32 else "total_bytes_int8"
    fits = layer_table(BatteryNet((w, w)), budget)[key] <= budget
    fails = layer_table(BatteryNet((w + 1, w + 1)), budget)[key] > budget
    assert fits and fails, f"quadratic answer {w} disagrees with layer_table"
    return w, (-8 + math.sqrt(64 - 4 * c)) / 2


def bench_summary():
    """Median round trip and server time from the Mission 3 benchmark files, if present."""
    out = []
    for path in sorted(glob.glob("results/bench_*.csv")):
        with open(path) as fh:
            rows = list(csv.DictReader(fh))[1:]          # skip the cold first request
        if rows and "server_total" in rows[0]:
            out.append((os.path.basename(path),
                        float(np.median([float(r["round_trip"]) for r in rows])),
                        float(np.median([float(r["server_total"]) for r in rows])),
                        float(np.median([float(r["inference"]) for r in rows]))))
    return out


def board_time_us(macs):
    return {k: macs * c / CPU_HZ * 1e6 for k, c in CYCLES_PER_MAC.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--widths", type=int, nargs="+", default=[32, 128, 256, 512, 2048])
    a = ap.parse_args()
    os.makedirs("docs", exist_ok=True); os.makedirs("results", exist_ok=True)
    os.makedirs("plots", exist_ok=True)
    md = ["# Mission 4 results (generated by `mission4.py`, do not edit by hand)\n",
          f"SRAM budget: 300 KB read as 300 x 1024 = {SRAM_BUDGET_BYTES:,} bytes. "
          f"PSRAM: 8 MB = {PSRAM_BYTES:,} bytes.\n"]

    # 1. Our deployed model ---------------------------------------------------------------
    cfg = json.load(open("model/config.json"))
    net = BatteryNet(tuple(cfg["hidden"]))
    info = layer_table(net)
    act = peak_activation_values(net)
    arch = " -> ".join([str(len(FEATURES))] + [str(h) for h in cfg["hidden"]] + ["1"])
    md += [f"## 1. Our model: {arch} (validation MAE {cfg['val_mae']} days)\n",
           "| Layer | in | out | params | bytes f32 | bytes int8 | MACs |", "|---|---|---|---|---|---|---|"]
    for l in info["layers"]:
        md.append(f"| {l['name']} | {l['in']} | {l['out']} | {l['params']:,} | {l['bytes_f32']:,} "
                  f"| {l['params'] * BYTES_INT8:,} | {l['macs']:,} |")
    md.append(f"| **total** | | | **{info['total_params']:,}** | **{info['total_bytes_f32']:,}** "
              f"| **{info['total_bytes_int8']:,}** | **{info['total_macs']:,}** |\n")
    md += [f"- Weights and biases: {fmt_bytes(info['total_bytes_f32'])} as float32, "
           f"{fmt_bytes(info['total_bytes_int8'])} as int8.",
           f"- Largest activation memory at once: {act} values (one layer's input plus output) = "
           f"{act * BYTES_F32} B as float32, {act * BYTES_INT8} B as int8.",
           f"- Total working set (weights + peak activations), float32: "
           f"{fmt_bytes(info['total_bytes_f32'] + act * BYTES_F32)} = "
           f"{(info['total_bytes_f32'] + act * BYTES_F32) / SRAM_BUDGET_BYTES:.2%} of the 300 KB budget.",
           f"- Fits in 300 KB SRAM: float32 {tick(info['fits_300kb_sram_f32'])}, "
           f"int8 {tick(info['fits_300kb_sram_int8'])}.\n"]

    # 2. Width table -------------------------------------------------------------------------
    md += ["## 2. 5 -> w -> w -> 1 at different widths\n",
           "| w | params | float32 | int8 | 300 KB SRAM f32 | 300 KB SRAM int8 | 8 MB PSRAM f32 | "
           "8 MB PSRAM int8 | MACs |", "|---|---|---|---|---|---|---|---|---|"]
    table = []
    for w in a.widths:
        t = layer_table(BatteryNet((w, w)))
        assert t["total_params"] == params_w(w), "closed form disagrees with layer_table"
        row = dict(w=w, params=t["total_params"], bytes_f32=t["total_bytes_f32"],
                   bytes_int8=t["total_bytes_int8"], fits_sram_f32=t["fits_300kb_sram_f32"],
                   fits_sram_int8=t["fits_300kb_sram_int8"],
                   fits_psram_f32=t["total_bytes_f32"] <= PSRAM_BYTES,
                   fits_psram_int8=t["total_bytes_int8"] <= PSRAM_BYTES, macs=t["total_macs"])
        table.append(row)
        md.append(f"| {w} | {row['params']:,} | {fmt_bytes(row['bytes_f32'])} | {fmt_bytes(row['bytes_int8'])} "
                  f"| {tick(row['fits_sram_f32'])} | {tick(row['fits_sram_int8'])} "
                  f"| {tick(row['fits_psram_f32'])} | {tick(row['fits_psram_int8'])} | {row['macs']:,} |")
    with open("results/mission4_widths.csv", "w", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(table[0])); wr.writeheader(); wr.writerows(table)
    md.append("\nParameters grow as w^2 + 8w + 1 and MACs as w^2 + 6w: doubling the width roughly "
              "quadruples memory and compute.\n")

    # 3. Exact boundary ------------------------------------------------------------------
    md += ["## 3. The exact width where the weights stop fitting\n",
           "Solve bytes_per_param x (w^2 + 8w + 1) <= budget with the quadratic formula, take the floor, "
           "then check w and w+1 on real networks with `layer_table`.\n",
           "| Budget | Precision | Real root | Last width that fits | First width that does not |",
           "|---|---|---|---|---|"]
    for budget, name in [(SRAM_BUDGET_BYTES, "300 x 1024 = 307,200 B (used)"), (300_000, "300,000 B")]:
        for b, prec in [(BYTES_F32, "float32"), (BYTES_INT8, "int8")]:
            w, root = largest_fitting_width(budget, b)
            md.append(f"| {name} | {prec} | {root:.2f} | {w} ({b * params_w(w):,} B) "
                      f"| {w + 1} ({b * params_w(w + 1):,} B) |")
    md.append("\nint8 fits about twice the width of float32 (4x fewer bytes, and size grows as w^2, "
              "so width grows by sqrt(4) = 2).\n")

    # 4. Time on the board -----------------------------------------------------------------
    md += ["## 4. Estimated time for one prediction on the ESP32-S3\n",
           f"Assumption: {CPU_HZ / 1e6:.0f} MHz, one core. Cycles per float32 MAC from Espressif's ESP-DSP "
           "benchmarks (`dsps_dotprod_f32`, N = 256): 432 cycles optimised, 1311 cycles plain C on the "
           "ESP32-S3. Time = MACs x cycles per MAC / clock. ReLU and loop overhead are ignored, so we "
           f"also show a {OVERHEAD_FACTOR:.0f}x margin. This is an estimate, not a measurement.\n",
           "| Model | MACs | optimised | plain C | plain C with margin |", "|---|---|---|---|---|"]
    for label, m in [(f"ours ({arch})", info["total_macs"])] + [(f"w = {r['w']}", r["macs"]) for r in table]:
        t = board_time_us(m)
        md.append(f"| {label} | {m:,} | {t['optimised (ESP-DSP)']:,.1f} us | {t['plain C']:,.1f} us "
                  f"| {t['plain C'] * OVERHEAD_FACTOR:,.1f} us |")

    # 5. Against the Mission 3 measurements ------------------------------------------------
    bench = bench_summary()
    ours_us = board_time_us(info["total_macs"])["plain C"] * OVERHEAD_FACTOR
    if bench:
        md += ["\n## 5. On the board against calling our server (Mission 3 measurements)\n",
               "| Benchmark file | round trip p50 | server_total p50 | inference p50 | round trip / on-board |",
               "|---|---|---|---|---|"]
        for name, rt, st, inf in bench:
            md.append(f"| {name} | {rt:,.1f} ms | {st:.3f} ms | {inf:.3f} ms | {rt * 1000 / ours_us:,.0f}x |")
        md.append(f"\nOn-board figure used: {ours_us:.1f} us (plain C with margin). The benchmark files "
                  "were measured on the 8,8 model; inference was a small part of server_total either way.\n")

    # Plot -------------------------------------------------------------------------------------
    try:
        import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
        ws = np.arange(8, 2049, 8)
        p = ws ** 2 + 8 * ws + 1
        fig, ax = plt.subplots(figsize=(7, 4.2))
        ax.plot(ws, p * BYTES_F32, label="float32 weights")
        ax.plot(ws, p * BYTES_INT8, label="int8 weights")
        ax.axhline(SRAM_BUDGET_BYTES, ls="--", c="gray"); ax.text(10, SRAM_BUDGET_BYTES * 1.15, "300 KB SRAM")
        ax.axhline(PSRAM_BYTES, ls=":", c="gray"); ax.text(10, PSRAM_BYTES * 1.15, "8 MB PSRAM")
        for b, c in [(BYTES_F32, "C0"), (BYTES_INT8, "C1")]:
            w, _ = largest_fitting_width(SRAM_BUDGET_BYTES, b); ax.axvline(w, c=c, lw=0.8)
            ax.text(w * 1.04, 3e3, f"w={w}", color=c)
        ax.scatter([r["w"] for r in table], [r["bytes_f32"] for r in table], c="C0", zorder=3)
        ax.set_xscale("log", base=2); ax.set_yscale("log")
        ax.set_xlabel("hidden width w  (5 -> w -> w -> 1)"); ax.set_ylabel("bytes")
        ax.set_title("Weight memory against width, ESP32-S3 limits"); ax.legend(loc="lower right")
        fig.tight_layout(); fig.savefig("plots/mission4_memory.png", dpi=150)
        md.append("![Weight memory against width](../plots/mission4_memory.png)\n")
    except ImportError:
        print("matplotlib not installed: skipped the plot")

    text = "\n".join(md)
    open("docs/mission4_results.md", "w").write(text + "\n")
    print(text)
    print("\nwrote docs/mission4_results.md, results/mission4_widths.csv, plots/mission4_memory.png")


if __name__ == "__main__":
    main()
